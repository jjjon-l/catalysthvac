"""Build paste-ready Elementor snippets and the local preview.

Sources (edit these):
  elementor/global.css      component CSS (single source of truth)
  elementor/cx-header.html  header markup
  elementor/cx-footer.html  footer + mobile call bar markup
  elementor/icons/*.svg     service icons
  preview/*.src.html        preview page bodies (+ preview/_base.css)

Outputs (paste these into Elementor HTML widgets):
  elementor/out/cx-styles.html   -> "CX – Styles" saved template
  elementor/out/cx-header.html   -> "CX – Header" saved template
  elementor/out/cx-footer.html   -> "CX – Footer" saved template
  elementor/out/icons/*.html     -> inline icon markup for cards
  preview/*.html                 -> local previews, everything inlined

Run from anywhere: python3 elementor/build.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EL = ROOT / "elementor"
OUT = EL / "out"
(OUT / "icons").mkdir(parents=True, exist_ok=True)

css = (EL / "global.css").read_text()
header = (EL / "cx-header.html").read_text()
footer = (EL / "cx-footer.html").read_text()
icons = {p.stem: p.read_text().strip() for p in sorted((EL / "icons").glob("*.svg"))}

FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?'
    'family=Barlow+Condensed:wght@600;700&family=Inter:wght@400;600&display=swap">\n'
)
GENERATED = "<!-- Generated by elementor/build.py. Edit the source files, not this. -->\n"

(OUT / "cx-styles.html").write_text(GENERATED + FONTS + "<style>\n" + css + "</style>\n")
(OUT / "cx-header.html").write_text(GENERATED + header)
(OUT / "cx-footer.html").write_text(GENERATED + footer)
for name, svg in icons.items():
    (OUT / "icons" / f"{name}.html").write_text(f'<span class="cx-icon">{svg}</span>\n')


def inline_icons(html: str) -> str:
    return re.sub(r"\{\{icon:([a-z0-9-]+)\}\}", lambda m: icons[m.group(1)], html)


PREVIEW_LINKS = {"/": "home.html", "/ac-repair/": "ac-repair.html", "/ac-replacement/": "ac-replacement.html",
                 "/heating-repair/": "heating-repair.html"}

base = FONTS + "<style>\n" + (ROOT / "preview" / "_base.css").read_text() + "</style>\n<style>\n" + css + "</style>\n"
for src in sorted((ROOT / "preview").glob("*.src.html")):
    page = (src.read_text()
            .replace("<!--__BASE__-->", base)
            .replace("<!--__HEADER__-->", header)
            .replace("<!--__FOOTER__-->", footer))
    out = src.with_name(src.name.replace(".src.html", ".html"))
    # Preview-only: point links at pages that exist as previews (GitHub Pages)
    for href, local in PREVIEW_LINKS.items():
        page = page.replace(f'href="{href}"', f'href="{local}"')
    out.write_text(inline_icons(page))
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size:,} bytes")

for f in sorted(OUT.glob("*.html")):
    print(f"{f.relative_to(ROOT)}: {f.stat().st_size:,} bytes")
