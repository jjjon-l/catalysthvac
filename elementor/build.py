"""Build paste-ready Elementor snippets and the local preview.

Sources (edit these):
  elementor/global.css      component CSS (single source of truth)
  elementor/cx-header.html  header markup
  elementor/cx-footer.html  footer + mobile call bar markup
  elementor/icons/*.svg     service icons
  preview/*.src.html        preview page bodies (+ preview/_base.css)
  elementor/seo/site.json   business facts (published only when verified)
  elementor/seo/pages.json  per-page title, meta, breadcrumb, service

Outputs (paste these into Elementor HTML widgets):
  elementor/out/cx-styles.html   -> "CX – Styles" saved template
  elementor/out/cx-header.html   -> "CX – Header" saved template
  elementor/out/cx-footer.html   -> "CX – Footer" saved template
  elementor/out/icons/*.html     -> inline icon markup for cards
  elementor/out/seo/*.html       -> per-page JSON-LD schema (HTML widget on that page)
  elementor/out/seo-register.md  -> titles/metas for the SEO plugin + SEO checks
  preview/*.html                 -> local previews, everything inlined

Run from anywhere: python3 elementor/build.py
"""
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EL = ROOT / "elementor"
OUT = EL / "out"
(OUT / "icons").mkdir(parents=True, exist_ok=True)
(OUT / "seo").mkdir(parents=True, exist_ok=True)

_spec = importlib.util.spec_from_file_location("seo", EL / "seo" / "seo.py")
seo = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(seo)
site = json.loads((EL / "seo" / "site.json").read_text())
pages = json.loads((EL / "seo" / "pages.json").read_text())

css = (EL / "global.css").read_text()
header = (EL / "cx-header.html").read_text()
footer = (EL / "cx-footer.html").read_text()
icons = {p.stem: p.read_text().strip() for p in sorted((EL / "icons").glob("*.svg"))}

FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?'
    'family=Barlow+Condensed:wght@600;700&family=Inter:wght@400;600&display=swap">\n'
)
GENERATED = "<!-- Generated by elementor/build.py. Edit the source files, not this. -->\n"

(OUT / "cx-styles.html").write_text(GENERATED + FONTS + "<style>\n" + css + "</style>\n")
(OUT / "cx-header.html").write_text(GENERATED + header)
(OUT / "cx-footer.html").write_text(GENERATED + footer)
for name, svg in icons.items():
    (OUT / "icons" / f"{name}.html").write_text(f'<span class="cx-icon">{svg}</span>\n')


def inline_icons(html: str) -> str:
    return re.sub(r"\{\{icon:([a-z0-9-]+)\}\}", lambda m: icons[m.group(1)], html)


PREVIEW_LINKS = {"/": "home.html", "/ac-repair/": "ac-repair.html", "/ac-replacement/": "ac-replacement.html",
                 "/heating-repair/": "heating-repair.html"}

base = FONTS + "<style>\n" + (ROOT / "preview" / "_base.css").read_text() + "</style>\n<style>\n" + css + "</style>\n"
report = []
for src in sorted((ROOT / "preview").glob("*.src.html")):
    key = src.name.replace(".src.html", "")
    meta = pages[key]
    page = (src.read_text()
            .replace("<!--__HEADER__-->", header)
            .replace("<!--__FOOTER__-->", footer))
    graph, omitted = seo.build_graph(site, key, meta, seo.extract_faqs(page))
    schema = seo.jsonld_script(graph)
    (OUT / "seo" / f"{key}.html").write_text(GENERATED + schema)
    report.append((key, meta, seo.lint(page, meta), omitted, graph))
    page = (page.replace("<!--__SEO__-->", seo.head_tags(site, meta) + schema)
                .replace("<!--__BASE__-->", base))
    out = src.with_name(f"{key}.html")
    # Preview-only: point links at pages that exist as previews (GitHub Pages)
    for href, local in PREVIEW_LINKS.items():
        page = page.replace(f'href="{href}"', f'href="{local}"')
    out.write_text(inline_icons(page))
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size:,} bytes")


def write_register():
    rows, notes = [], []
    for key, meta, l, omitted, graph in report:
        types = ", ".join(n["@type"] for n in graph["@graph"])
        flags = []
        if l["title_len"] > 60: flags.append(f"title {l['title_len']} chars (may truncate)")
        if not 70 <= l["desc_len"] <= 160: flags.append(f"meta {l['desc_len']} chars")
        if l["h1"] != 1: flags.append(f"{l['h1']} H1s")
        if l["heading_skips"]: flags.append("heading skips " + ", ".join(l["heading_skips"]))
        if l["img_no_alt"]: flags.append(f"{l['img_no_alt']} img without alt")
        cell = lambda s: s.replace("|", "\\|")
        rows.append(f"| `{meta['path']}` | {cell(meta['title'])} | {cell(meta['description'])} | {types} | "
                    f"{l['placeholders']} | {'; '.join(flags) or 'OK'} |")
        if omitted:
            notes.append(f"- `{meta['path']}`: left out until verified: {', '.join(omitted)}")
    unverified = [k for k, v in site.items() if isinstance(v, dict) and v.get("value") and not v.get("verified")]
    text = [
        "# SEO Register (generated by `elementor/build.py`, do not edit)",
        "",
        "Paste **Title** and **Meta** into the SEO plugin for each page. Paste `elementor/out/seo/<page>.html` into an HTML widget on that page.",
        "",
        "| URL | Title | Meta description | Schema | Placeholders | Checks |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "## Facts held out of schema (flip `verified` in `elementor/seo/site.json` once approved)",
        *(f"- **{k}**: {site[k]['source']}" for k in unverified),
        "",
        "## Per page",
        *notes,
        "",
    ]
    (OUT / "seo-register.md").write_text("\n".join(text))


write_register()
for f in sorted(OUT.glob("*.html")):
    print(f"{f.relative_to(ROOT)}: {f.stat().st_size:,} bytes")
